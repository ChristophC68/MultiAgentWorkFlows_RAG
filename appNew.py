# Define chunking logic with overlap
def chunk_text(text, chunk_size=200, overlap=50):
    """
    Split text into overlapping chunks based on sentence boundaries.

    Returns:
        list: List of text chunks
    """
    print("\nIn chunk_text")
    
    try:
        chunks = []
        current_chunk = []
        current_length = 0
        
        # split the text into sentences
        sentences = sent_tokenize(text)

        for sentence in sentences:
            
            # split each sentence into words
            words = sentence.split()
            sentence_len = len(words)

            # If adding this sentence exceeds chunk size, save current chunk
            if current_length + sentence_len > chunk_size:
                chunks.append(" ".join(current_chunk))
                
                # Keep last 'overlap' words for context continuity
                current_chunk = current_chunk[-overlap:] if overlap else []
                current_length = sum(len(s.split()) for s in current_chunk)

            current_chunk.extend(words)
            current_length += sentence_len

        # Add the final chunk if it exists
        if current_chunk:
            chunks.append(" ".join(current_chunk))

        return chunks
    
    except Exception as e:
            print(f"Error Type: {type(e).__name__}")
            print(f"Error Message: {e}")
            return []


# Utility: Clean extracted text
def clean_text(text):
    """
    Clean extracted PDF text by removing noise and normalizing formatting.

    Args:
        text (str): Raw text extracted from PDF

    Returns:
        str: Cleaned text ready for chunking
    """
    #logger.info("Starting text data cleaning routines...")
    
    # Remove excessive line breaks
    text = re.sub(r"\n+", "\n", text)
    
    # Remove excessive whitespace
    text = re.sub(r"\s{2,}", " ", text)
    
    # Remove page number artifacts
    text = re.sub(r"Page \d+", "", text, flags=re.IGNORECASE)
    
    # Strip out the [image] markers and replace them with a space
    text = text.replace("[image]", " ")

    # Clean up any accidental double spaces caused by the removal
    text = " ".join(text.split())
    
    # Match any digit(s) followed by a period that comes right after a space or sentence end
    # Example matched: " This is a sentence. 1. This is the next item."
    pattern = r"\b\d+\.\s+"
    text = re.sub(pattern, "", text)
    
    # Replace the bullet symbol with a comma and a space
    text = text.replace(" • ", ", ")
    
    # Replace the bullet symbol with a comma and a space
    text = text.replace("", "")
     
    # we dont need commas after a colon
    text = text.replace(":,", ":")
    
    # we dont need commas after a fullstop
    text = text.replace(".,", ".")
    
    # typically a contents section ends up with a long series of dots, or spaces
    text = re.sub(r"\.{2,}", ".", text)
    text = re.sub(r" {2,}", ".", text)
    
    # does this remove content type indexes?
    text = re.sub(r"\d+\s+.*?\s+\.\s+\d+", "", text)
        
    return text.strip()


