def do_chunking(documents_to_chunk, chunk_size=100, chunk_overlap=50):  
    
    """_summary_
    Receives input of a list of individual documents in the following form:
    {"source": str(txt_filename), "text": extracted_text, "publication date": 0}
    
    Returns:
    
    """

    try: 
        # Beginning chunking for all documents
        all_chunks = []
        for doc in documents_to_chunk:
            # call helper function
            print(f"Chunking for {doc["source"]} beginning")
            chunks = chunk_text(doc["text"], chunk_size, chunk_overlap)
                    
            # Ensure your DataFrame column names match 
            # all_chunks need to have these columns 'source','chunk_id','text'
            for i, chunk in enumerate(chunks):
                all_chunks.append({
                    "source": doc["source"],
                    "chunk_id": i,
                    "text": chunk
                })
            
            # all_chunks created by do_chunking routine: {"source": doc["source"], "chunk_id": i, "text": chunk}
            print(f"Chunking Statistics:")
            print(f"{doc["source"]} Total chunks created: {len(chunks)}")             
            print("\n" + "="*30)
                        
        return all_chunks
            
    except Exception as e:
        print("\n" + "="*40 + " ERROR CAUGHT " + "="*40)
        print(f"Error Type: {type(e).__name__}")
        print(f"Error Message: {e}")
